import uuid
from datetime import datetime
from typing import Literal, Self

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field, model_validator

from app.modules.attendance.state_machine import AttendanceState, EventType
from app.modules.geolocation.schemas import Latitude, Longitude

ValidationStatus = Literal["PENDING", "VALIDATED", "REJECTED", "FLAGGED_FOR_REVIEW"]
Source = Literal["MOBILE_GPS", "MANUAL", "OFFLINE_SYNC"]
SubjectKindLiteral = Literal["STUDENT", "STAFF"]


class AttendanceEventCreate(BaseModel):
    """An attendance action performed by the caller on their own phone."""

    model_config = ConfigDict(extra="forbid")

    idempotency_key: uuid.UUID = Field(
        description="Generated by the app per action; retries must reuse it"
    )
    event_type: EventType
    campus_id: uuid.UUID
    occurred_at: AwareDatetime = Field(description="When the user tapped the action")
    latitude: Latitude
    longitude: Longitude
    accuracy_m: float = Field(ge=0, le=10_000)
    location_captured_at: AwareDatetime
    is_mock: bool | None = None
    device_id: uuid.UUID | None = None
    as_subject: SubjectKindLiteral | None = Field(
        default=None,
        description="Only needed when the account is both a student and a staff member",
    )


class ManualEventCreate(BaseModel):
    """An event entered by a School Admin for someone else (no phone, no GPS)."""

    model_config = ConfigDict(extra="forbid")

    idempotency_key: uuid.UUID
    event_type: EventType
    campus_id: uuid.UUID
    student_id: uuid.UUID | None = None
    staff_id: uuid.UUID | None = None
    reason: str = Field(min_length=3, max_length=500)
    occurred_at: AwareDatetime | None = None

    @model_validator(mode="after")
    def _one_subject(self) -> Self:
        if (self.student_id is None) == (self.staff_id is None):
            raise ValueError("Provide exactly one of 'student_id' or 'staff_id'")
        return self


class ReviewDecision(BaseModel):
    model_config = ConfigDict(extra="forbid")

    decision: Literal["VALIDATED", "REJECTED"]
    note: str = Field(min_length=3, max_length=500)


class LocationOut(BaseModel):
    latitude: float
    longitude: float
    accuracy_m: float | None


class AttendanceEventOut(BaseModel):
    id: uuid.UUID
    event_type: EventType
    source: Source
    campus_id: uuid.UUID
    student_id: uuid.UUID | None
    staff_id: uuid.UUID | None
    actor_user_id: uuid.UUID
    state_before: AttendanceState
    state_after: AttendanceState
    validation_status: ValidationStatus
    validation_reasons: list[str]
    geofence_result: str
    distance_to_geofence_m: float | None
    occurred_at: datetime
    received_at: datetime
    location: LocationOut | None = Field(
        default=None, description="Only returned to School Admins"
    )


class SubjectStateOut(BaseModel):
    subject: SubjectKindLiteral
    subject_id: uuid.UUID
    state: AttendanceState
    allowed_events: list[EventType]
    last_event_id: uuid.UUID | None


class OfflineBatch(BaseModel):
    model_config = ConfigDict(extra="forbid")

    events: list[AttendanceEventCreate] = Field(min_length=1, max_length=50)


class BatchItemOut(BaseModel):
    idempotency_key: uuid.UUID
    outcome: Literal["created", "replayed", "error"]
    status_code: int
    event: AttendanceEventOut | None = None
    error: str | None = None


class OfflineBatchResult(BaseModel):
    results: list[BatchItemOut]


class GuardedStudentOut(BaseModel):
    student_id: uuid.UUID
    full_name: str
    student_code: str
    state: AttendanceState
    last_event_id: uuid.UUID | None
