import uuid
from datetime import datetime
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

from app.modules.identity.models import DevicePlatform, DeviceStatus
from app.modules.institutions.models import InstitutionRole


class LoginRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    # Only the email is trimmed: whitespace in a password is significant.
    email: Annotated[
        str,
        StringConstraints(
            strip_whitespace=True, min_length=3, max_length=320, pattern=r"^[^@\s]+@[^@\s]+$"
        ),
    ]
    password: str = Field(min_length=1, max_length=1024)


class RefreshRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    refresh_token: str = Field(min_length=1, max_length=4096)


class TokenResponse(BaseModel):
    access_token: str
    refresh_token: str
    token_type: Literal["bearer"] = "bearer"  # noqa: S105 - OAuth2 token kind
    expires_in: int = Field(description="Access token lifetime in seconds")


class MembershipOut(BaseModel):
    institution_id: uuid.UUID
    institution_name: str
    roles: list[InstitutionRole]


class MeResponse(BaseModel):
    id: uuid.UUID
    email: str
    full_name: str
    is_platform_admin: bool
    memberships: list[MembershipOut]


class DeviceRegister(BaseModel):
    model_config = ConfigDict(extra="forbid")

    installation_id: str = Field(
        min_length=8, max_length=200, description="Random id generated by the app on first launch"
    )
    platform: DevicePlatform
    model: str | None = Field(default=None, max_length=100)
    app_version: str | None = Field(default=None, max_length=50)
    push_token: str | None = Field(
        default=None, max_length=300, description="Expo push token, if notifications are allowed"
    )


class DeviceOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    installation_id: str
    platform: DevicePlatform
    model: str | None
    app_version: str | None
    status: DeviceStatus
    registered_at: datetime
    last_seen_at: datetime | None


Password = Annotated[str, StringConstraints(min_length=12, max_length=128)]


class AccountCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")

    email: Annotated[
        str,
        StringConstraints(
            strip_whitespace=True, min_length=3, max_length=320, pattern=r"^[^@\s]+@[^@\s]+$"
        ),
    ]
    full_name: str = Field(min_length=1, max_length=200)
    initial_password: Password


class AccountOut(BaseModel):
    id: uuid.UUID
    email: str
    full_name: str


class PasswordChange(BaseModel):
    model_config = ConfigDict(extra="forbid")

    current_password: str = Field(min_length=1, max_length=1024)
    new_password: Password
