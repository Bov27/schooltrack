CREATE INDEX notifications_dispatch_idx ON notifications (next_attempt_at) WHERE status = 'PENDING';
CREATE INDEX notifications_recipient_idx ON notifications (recipient_user_id, created_at DESC);

-- Append-only. institution_id is NULL for platform-level actions, which are
-- therefore invisible to the runtime role.
CREATE TABLE audit_logs (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    institution_id  uuid REFERENCES institutions(id),
    actor_user_id   uuid REFERENCES users(id),
    action          text NOT NULL,              -- e.g. 'attendance_event.validation_changed'
    entity_type     text NOT NULL,
    entity_id       text,
    changes         jsonb,
    ip_address      inet,
    user_agent      text,
    request_id      text,
    occurred_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_logs_tenant_time_idx ON audit_logs (institution_id, occurred_at DESC);

CREATE OR REPLACE FUNCTION audit_logs_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'audit_logs is append-only' USING ERRCODE = 'insufficient_privilege';
END;
$$;
CREATE TRIGGER audit_logs_append_only
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION audit_logs_append_only();

-- =============================================================================
-- Row-Level Security
-- =============================================================================
-- One policy shape for every table that has institution_id. USING filters
-- reads, WITH CHECK rejects writes that would land in another tenant.
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'institution_memberships', 'user_roles', 'campuses', 'geofences',
        'students', 'staff', 'guardians', 'student_guardians', 'classrooms',
        'classroom_teachers', 'enrollments', 'schedules', 'attendance_events',
        'attendance_subject_states', 'attendance_records', 'excuses',
        'notifications', 'audit_logs'
    ] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format(
            'CREATE POLICY tenant_isolation ON %I '
            'USING (institution_id = app_current_institution_id()) '
            'WITH CHECK (institution_id = app_current_institution_id())', t);
    END LOOP;
END;
$$;

-- The institutions table is keyed by id rather than institution_id.
ALTER TABLE institutions ENABLE ROW LEVEL SECURITY;
ALTER TABLE institutions FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON institutions
    USING (id = app_current_institution_id())
    WITH CHECK (id = app_current_institution_id());

-- Before a tenant is chosen (login, GET /institutions) the backend sets only
-- app.current_user_id. These read-only policies let a user see their own
-- memberships, roles and the institutions they belong to — nothing else.
-- Permissive policies are OR-ed with tenant_isolation.
CREATE POLICY own_memberships_read ON institution_memberships FOR SELECT
    USING (user_id = app_current_user_id());
CREATE POLICY own_roles_read ON user_roles FOR SELECT
    USING (user_id = app_current_user_id());
CREATE POLICY member_institutions_read ON institutions FOR SELECT
    USING (id IN (SELECT m.institution_id FROM institution_memberships m
                  WHERE m.user_id = app_current_user_id() AND m.status = 'ACTIVE'));

-- =============================================================================
-- Privileges for the runtime role
-- =============================================================================
-- schooltrack_app is created by infrastructure/docker/postgres/initdb and by
-- the deployment scripts. It is LOGIN, NOSUPERUSER, NOBYPASSRLS.
GRANT USAGE ON SCHEMA public TO schooltrack_app;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA public TO schooltrack_app;
GRANT DELETE ON
    user_roles, student_guardians, classroom_teachers, devices, notifications
    TO schooltrack_app;
REVOKE UPDATE ON audit_logs FROM schooltrack_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO schooltrack_app;
