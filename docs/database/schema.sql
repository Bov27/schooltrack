-- =============================================================================
-- SchoolTrack — reference database schema (Week 1 design artifact)
-- =============================================================================
-- This file is the reviewed design of the initial schema. It is NOT executed by
-- the application: from Week 2 onward each part is implemented as an Alembic
-- migration (backend/migrations) together with its SQLAlchemy models and tests.
-- Keep this file and the migrations in sync until the migrations become the
-- single source of truth.
--
-- Conventions
--   * Primary keys are UUIDs generated by PostgreSQL (gen_random_uuid()).
--   * Every tenant-owned table has a NOT NULL institution_id, a composite
--     UNIQUE (institution_id, id) so that children can reference it with a
--     composite foreign key, and a Row-Level Security policy.
--   * Timestamps are TIMESTAMPTZ and stored in UTC.
--   * The runtime role (schooltrack_app) never owns tables and has no
--     BYPASSRLS, so policies always apply to it. FORCE ROW LEVEL SECURITY also
--     applies them to the table owner.
--   * The tenant for a transaction is set by the backend with
--       SET LOCAL app.current_institution_id = '<uuid>';
--     after it has resolved the institution from the authenticated user's
--     memberships. Without that setting, tenant tables return no rows.
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS citext;

-- -----------------------------------------------------------------------------
-- Tenant context helper
-- -----------------------------------------------------------------------------
-- Returns NULL when the setting is missing or empty, so policies fail closed.
CREATE OR REPLACE FUNCTION app_current_institution_id() RETURNS uuid
LANGUAGE sql STABLE AS $$
    SELECT NULLIF(current_setting('app.current_institution_id', true), '')::uuid
$$;

CREATE OR REPLACE FUNCTION app_current_user_id() RETURNS uuid
LANGUAGE sql STABLE AS $$
    SELECT NULLIF(current_setting('app.current_user_id', true), '')::uuid
$$;

-- -----------------------------------------------------------------------------
-- Enumerated types
-- -----------------------------------------------------------------------------
CREATE TYPE institution_role       AS ENUM ('SCHOOL_ADMIN', 'TEACHER', 'STUDENT', 'STAFF', 'GUARDIAN');
CREATE TYPE membership_status      AS ENUM ('INVITED', 'ACTIVE', 'SUSPENDED');
CREATE TYPE staff_type             AS ENUM ('TEACHER', 'ADMINISTRATIVE', 'SUPPORT');
CREATE TYPE enrollment_status      AS ENUM ('ACTIVE', 'WITHDRAWN', 'COMPLETED');
CREATE TYPE attendance_event_type  AS ENUM ('CHECK_IN', 'TEMPORARY_CHECK_OUT', 'RETURN', 'CHECK_OUT');
CREATE TYPE attendance_state       AS ENUM ('OUTSIDE', 'PRESENT', 'TEMPORARY_EXIT');
CREATE TYPE attendance_source      AS ENUM ('MOBILE_GPS', 'MANUAL', 'OFFLINE_SYNC');
CREATE TYPE geofence_result        AS ENUM ('INSIDE', 'OUTSIDE', 'NOT_EVALUATED');
CREATE TYPE validation_status      AS ENUM ('PENDING', 'VALIDATED', 'REJECTED', 'FLAGGED_FOR_REVIEW');
CREATE TYPE daily_attendance_status AS ENUM ('PRESENT', 'LATE', 'ABSENT', 'EXCUSED', 'PARTIAL');
CREATE TYPE excuse_status          AS ENUM ('SUBMITTED', 'APPROVED', 'REJECTED');
CREATE TYPE notification_status    AS ENUM ('PENDING', 'SENT', 'FAILED', 'CANCELLED');
CREATE TYPE device_platform        AS ENUM ('ANDROID', 'IOS', 'WEB');
CREATE TYPE device_status          AS ENUM ('ACTIVE', 'REVOKED');

-- =============================================================================
-- Global (non-tenant) tables
-- =============================================================================

-- Institutions are the tenants themselves. Readable by the runtime role only
-- for the current tenant; created and listed across tenants by the platform
-- role (see ADR-002).
CREATE TABLE institutions (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name        text NOT NULL,
    slug        citext NOT NULL UNIQUE,
    country     char(2) NOT NULL DEFAULT 'CO',
    timezone    text NOT NULL DEFAULT 'America/Bogota',
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

-- A person can belong to several institutions, so users are global.
CREATE TABLE users (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email           citext NOT NULL UNIQUE,
    password_hash   text,                       -- NULL until an invitation is accepted
    full_name       text NOT NULL,
    is_active       boolean NOT NULL DEFAULT true,
    last_login_at   timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

-- Super Admins are a platform concern, not an institution role.
CREATE TABLE platform_admins (
    user_id     uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    granted_at  timestamptz NOT NULL DEFAULT now(),
    granted_by  uuid REFERENCES users(id)
);

-- Devices belong to a user, not to an institution.
CREATE TABLE devices (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id          uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    installation_id  text NOT NULL,              -- generated by the mobile app on first launch
    platform         device_platform NOT NULL,
    model            text,
    app_version      text,
    push_token       text,
    status           device_status NOT NULL DEFAULT 'ACTIVE',
    registered_at    timestamptz NOT NULL DEFAULT now(),
    last_seen_at     timestamptz,
    UNIQUE (user_id, installation_id)
);

-- =============================================================================
-- Tenant-owned tables
-- =============================================================================

-- Membership of a user in an institution. Roles hang off the membership so
-- a role can never exist for an institution the user does not belong to.
CREATE TABLE institution_memberships (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id  uuid NOT NULL REFERENCES institutions(id) ON DELETE CASCADE,
    user_id         uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status          membership_status NOT NULL DEFAULT 'INVITED',
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (institution_id, user_id),
    UNIQUE (institution_id, id)
);

CREATE TABLE user_roles (
    institution_id  uuid NOT NULL,
    user_id         uuid NOT NULL,
    role            institution_role NOT NULL,
    granted_at      timestamptz NOT NULL DEFAULT now(),
    granted_by      uuid REFERENCES users(id),
    PRIMARY KEY (institution_id, user_id, role),
    FOREIGN KEY (institution_id, user_id)
        REFERENCES institution_memberships (institution_id, user_id) ON DELETE CASCADE
);

CREATE TABLE campuses (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id  uuid NOT NULL REFERENCES institutions(id) ON DELETE CASCADE,
    name            text NOT NULL,
    address         text,
    timezone        text,                        -- NULL = inherit from institution
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (institution_id, name),
    UNIQUE (institution_id, id)
);

-- Authorized areas. GEOGRAPHY keeps distances in metres on the WGS84 ellipsoid.
-- Polygon validity (closed ring, no self-intersection, reasonable area) is
-- checked by the geolocation service before insert (Week 3).
CREATE TABLE geofences (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id  uuid NOT NULL,
    campus_id       uuid NOT NULL,
    name            text NOT NULL,
    area            GEOGRAPHY(POLYGON, 4326) NOT NULL,
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    created_by      uuid REFERENCES users(id),
    UNIQUE (institution_id, id),
    FOREIGN KEY (institution_id, campus_id) REFERENCES campuses (institution_id, id)
);
CREATE INDEX geofences_area_gist ON geofences USING GIST (area);
CREATE INDEX geofences_campus_active_idx ON geofences (institution_id, campus_id) WHERE is_active;

CREATE TABLE students (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id  uuid NOT NULL,
    user_id         uuid REFERENCES users(id),   -- NULL for students without an app account
    student_code    text NOT NULL,
    full_name       text NOT NULL,
    date_of_birth   date,                        -- minors' data: see docs/security
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (institution_id, student_code),
    UNIQUE (institution_id, id),
    UNIQUE (institution_id, user_id),
    FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE CASCADE
);

CREATE TABLE staff (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id  uuid NOT NULL,
    user_id         uuid NOT NULL,
    employee_code   text NOT NULL,
    staff_type      staff_type NOT NULL,
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (institution_id, employee_code),
    UNIQUE (institution_id, user_id),
    UNIQUE (institution_id, id),
    FOREIGN KEY (institution_id, user_id)
        REFERENCES institution_memberships (institution_id, user_id)
);

CREATE TABLE guardians (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id  uuid NOT NULL,
    user_id         uuid NOT NULL,
    phone           text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (institution_id, user_id),
    UNIQUE (institution_id, id),
    FOREIGN KEY (institution_id, user_id)
        REFERENCES institution_memberships (institution_id, user_id)
);

-- Guardian authorization is explicit and auditable (Law 1581: minors' data).
CREATE TABLE student_guardians (
    institution_id      uuid NOT NULL,
    student_id          uuid NOT NULL,
    guardian_id         uuid NOT NULL,
    relationship        text NOT NULL,          -- e.g. 'MOTHER', 'FATHER', 'LEGAL_GUARDIAN'
    is_primary          boolean NOT NULL DEFAULT false,
    receives_alerts     boolean NOT NULL DEFAULT true,
    authorized_at       timestamptz NOT NULL DEFAULT now(),
    authorized_by       uuid REFERENCES users(id),
    PRIMARY KEY (institution_id, student_id, guardian_id),
    FOREIGN KEY (institution_id, student_id)  REFERENCES students  (institution_id, id) ON DELETE CASCADE,
    FOREIGN KEY (institution_id, guardian_id) REFERENCES guardians (institution_id, id) ON DELETE CASCADE
);

CREATE TABLE classrooms (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id  uuid NOT NULL,
    campus_id       uuid NOT NULL,
    name            text NOT NULL,              -- e.g. '7A'
    academic_period text NOT NULL,              -- e.g. '2027'
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (institution_id, campus_id, name, academic_period),
    UNIQUE (institution_id, id),
    FOREIGN KEY (institution_id, campus_id) REFERENCES campuses (institution_id, id)
);

CREATE TABLE classroom_teachers (
    institution_id  uuid NOT NULL,
    classroom_id    uuid NOT NULL,
    staff_id        uuid NOT NULL,
    is_homeroom     boolean NOT NULL DEFAULT false,
    PRIMARY KEY (institution_id, classroom_id, staff_id),
    FOREIGN KEY (institution_id, classroom_id) REFERENCES classrooms (institution_id, id) ON DELETE CASCADE,
    FOREIGN KEY (institution_id, staff_id)     REFERENCES staff      (institution_id, id) ON DELETE CASCADE
);

CREATE TABLE enrollments (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id  uuid NOT NULL,
    classroom_id    uuid NOT NULL,
    student_id      uuid NOT NULL,
    status          enrollment_status NOT NULL DEFAULT 'ACTIVE',
    starts_on       date NOT NULL,
    ends_on         date,
    CHECK (ends_on IS NULL OR ends_on >= starts_on),
    UNIQUE (institution_id, id),
    FOREIGN KEY (institution_id, classroom_id) REFERENCES classrooms (institution_id, id),
    FOREIGN KEY (institution_id, student_id)   REFERENCES students   (institution_id, id)
);
-- A student has at most one active enrollment per classroom.
CREATE UNIQUE INDEX enrollments_one_active_idx
    ON enrollments (institution_id, classroom_id, student_id) WHERE status = 'ACTIVE';

-- Expected attendance windows. Lateness is computed against these (Week 7).
CREATE TABLE schedules (
    id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id      uuid NOT NULL,
    classroom_id        uuid NOT NULL,
    weekday             smallint NOT NULL CHECK (weekday BETWEEN 1 AND 7),   -- ISO: 1 = Monday
    starts_at           time NOT NULL,
    ends_at             time NOT NULL,
    late_after_minutes  smallint NOT NULL DEFAULT 10 CHECK (late_after_minutes >= 0),
    CHECK (ends_at > starts_at),
    UNIQUE (institution_id, id),
    FOREIGN KEY (institution_id, classroom_id) REFERENCES classrooms (institution_id, id) ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- Attendance
-- -----------------------------------------------------------------------------
-- Immutable fact log. Exactly one subject (student or staff member). The actor
-- is who submitted the event: the subject on their own device, or a teacher or
-- admin for a manual entry.
CREATE TABLE attendance_events (
    id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id        uuid NOT NULL,
    campus_id             uuid NOT NULL,
    student_id            uuid,
    staff_id              uuid,
    actor_user_id         uuid NOT NULL REFERENCES users(id),
    device_id             uuid REFERENCES devices(id),
    event_type            attendance_event_type NOT NULL,
    source                attendance_source NOT NULL,
    state_before          attendance_state NOT NULL,
    state_after           attendance_state NOT NULL,
    occurred_at           timestamptz NOT NULL,           -- client clock, validated against received_at
    received_at           timestamptz NOT NULL DEFAULT now(),
    location              GEOGRAPHY(POINT, 4326),          -- NULL only for MANUAL events
    gps_accuracy_m        real CHECK (gps_accuracy_m IS NULL OR gps_accuracy_m >= 0),
    location_captured_at  timestamptz,
    is_mock_location      boolean,                        -- reported by the OS where supported
    geofence_id           uuid,
    geofence_result       geofence_result NOT NULL DEFAULT 'NOT_EVALUATED',
    distance_to_geofence_m real,
    idempotency_key       uuid NOT NULL,
    validation_status     validation_status NOT NULL DEFAULT 'PENDING',
    validation_reasons    jsonb NOT NULL DEFAULT '[]'::jsonb,
    manual_reason         text,
    CHECK (num_nonnulls(student_id, staff_id) = 1),
    CHECK (source = 'MANUAL' OR location IS NOT NULL),
    CHECK (source <> 'MANUAL' OR manual_reason IS NOT NULL),
    UNIQUE (institution_id, id),
    -- Retried requests with the same key are answered with the original event.
    UNIQUE (institution_id, actor_user_id, idempotency_key),
    FOREIGN KEY (institution_id, campus_id)   REFERENCES campuses  (institution_id, id),
    FOREIGN KEY (institution_id, student_id)  REFERENCES students  (institution_id, id),
    FOREIGN KEY (institution_id, staff_id)    REFERENCES staff     (institution_id, id),
    FOREIGN KEY (institution_id, geofence_id) REFERENCES geofences (institution_id, id)
);
CREATE INDEX attendance_events_student_time_idx
    ON attendance_events (institution_id, student_id, occurred_at DESC) WHERE student_id IS NOT NULL;
CREATE INDEX attendance_events_staff_time_idx
    ON attendance_events (institution_id, staff_id, occurred_at DESC) WHERE staff_id IS NOT NULL;
CREATE INDEX attendance_events_review_idx
    ON attendance_events (institution_id, validation_status)
    WHERE validation_status IN ('PENDING', 'FLAGGED_FOR_REVIEW');

-- Only validation_status and validation_reasons may change after insert
-- (review workflow); every such change is written to audit_logs by the
-- service layer. Deletes are never allowed.
CREATE OR REPLACE FUNCTION attendance_events_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'attendance_events is append-only' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF (to_jsonb(NEW) - 'validation_status' - 'validation_reasons')
       IS DISTINCT FROM (to_jsonb(OLD) - 'validation_status' - 'validation_reasons') THEN
        RAISE EXCEPTION 'attendance_events rows are immutable except for validation fields'
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER attendance_events_guard
    BEFORE UPDATE OR DELETE ON attendance_events
    FOR EACH ROW EXECUTE FUNCTION attendance_events_guard();

-- Current state per subject. The attendance service locks this row
-- (SELECT ... FOR UPDATE) to serialize concurrent events for one person,
-- checks the transition, inserts the event and updates the row in the same
-- transaction (ADR-004, Week 4).
CREATE TABLE attendance_subject_states (
    institution_id  uuid NOT NULL,
    student_id      uuid,
    staff_id        uuid,
    current_state   attendance_state NOT NULL DEFAULT 'OUTSIDE',
    last_event_id   uuid,
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(student_id, staff_id) = 1),
    FOREIGN KEY (institution_id, student_id)    REFERENCES students          (institution_id, id) ON DELETE CASCADE,
    FOREIGN KEY (institution_id, staff_id)      REFERENCES staff             (institution_id, id) ON DELETE CASCADE,
    FOREIGN KEY (institution_id, last_event_id) REFERENCES attendance_events (institution_id, id)
);
CREATE UNIQUE INDEX attendance_subject_states_student_uq
    ON attendance_subject_states (institution_id, student_id) WHERE student_id IS NOT NULL;
CREATE UNIQUE INDEX attendance_subject_states_staff_uq
    ON attendance_subject_states (institution_id, staff_id) WHERE staff_id IS NOT NULL;

-- Daily summary derived from events, schedules and excuses (recomputable).
CREATE TABLE attendance_records (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id   uuid NOT NULL,
    student_id       uuid,
    staff_id         uuid,
    attendance_date  date NOT NULL,
    status           daily_attendance_status NOT NULL,
    first_check_in   timestamptz,
    last_check_out   timestamptz,
    minutes_present  integer CHECK (minutes_present IS NULL OR minutes_present >= 0),
    computed_at      timestamptz NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(student_id, staff_id) = 1),
    UNIQUE (institution_id, id),
    FOREIGN KEY (institution_id, student_id) REFERENCES students (institution_id, id) ON DELETE CASCADE,
    FOREIGN KEY (institution_id, staff_id)   REFERENCES staff    (institution_id, id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX attendance_records_student_day_uq
    ON attendance_records (institution_id, student_id, attendance_date) WHERE student_id IS NOT NULL;
CREATE UNIQUE INDEX attendance_records_staff_day_uq
    ON attendance_records (institution_id, staff_id, attendance_date) WHERE staff_id IS NOT NULL;

CREATE TABLE excuses (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institution_id  uuid NOT NULL,
    student_id      uuid NOT NULL,
    starts_on       date NOT NULL,
    ends_on         date NOT NULL,
    reason          text NOT NULL,
    status          excuse_status NOT NULL DEFAULT 'SUBMITTED',
    submitted_by    uuid NOT NULL REFERENCES users(id),
    submitted_at    timestamptz NOT NULL DEFAULT now(),
    reviewed_by     uuid REFERENCES users(id),
    reviewed_at     timestamptz,
    CHECK (ends_on >= starts_on),
    CHECK ((status = 'SUBMITTED') = (reviewed_at IS NULL)),
    UNIQUE (institution_id, id),
    FOREIGN KEY (institution_id, student_id) REFERENCES students (institution_id, id) ON DELETE CASCADE
);

